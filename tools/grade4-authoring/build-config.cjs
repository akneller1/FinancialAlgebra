// Writes worksheet-generator/grade4/config.js (the Grade 4 settings for the shared elementary runtime) from games.json.
// Usage: node tools/grade4-authoring/build-config.cjs
const fs = require('fs'), path = require('path');
const ROOT = process.env.G4_ROOT || path.resolve(__dirname, '../..');
const G = require('./games.json').games;
const games = {};
G.forEach(g => { const c = Object.assign({}, g); delete c.id; delete c.thumb; delete c.description; delete c.generated; delete c.team; games[g.id] = c; });
const out = `/* 4th Grade Math settings for the shared elementary runtime (worksheet-generator/elementary/).
   Generated by tools/grade4-authoring/build-config.cjs from games.json. Load this before elementary/el-core.js.
   A new elementary course needs only its own copy of this file and three thin pages (games, flashcards, Understanding Check). */
window.MK_ELEMENTARY = {
  course: 'math4',
  label: 'Grade 4',
  metaPath: '../question-banks/math4/meta/',
  flashcards: 'grade4/flashcards/',
  zoomKey: 'el-zoom-math4',
  answerHint: 'Fractions: 3/4 · Mixed numbers: 2 1/2 · Remainders: 12 R 3 · Decimals: 0.75 · Money: $4.50',
  games: ${JSON.stringify(games, null, 2).replace(/\n/g, '\n  ')}
};
`;
fs.mkdirSync(path.join(ROOT, 'worksheet-generator/grade4'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'worksheet-generator/grade4/config.js'), out);
console.log('wrote worksheet-generator/grade4/config.js (' + G.length + ' games)');
