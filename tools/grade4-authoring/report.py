"""Grade 4 standards coverage report: docs/math4/COVERAGE.md and docs/math4/COVERAGE.csv.
Counts come from the published bank (question-banks/math4/*.json) and its meta files, not from the outline alone."""
import collections, csv, glob, json, os
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
O = json.load(open(os.path.join(HERE, "outline.json"), encoding="utf-8"))
LV = ["cp2", "cp1", "honors"]
LN = {"cp2": "Remedial", "cp1": "Standard", "honors": "Advanced"}

skills, std_skills = {}, collections.defaultdict(list)
for ui, u in enumerate(O["units"], 1):
    for si, (name, stds) in enumerate(u["skills"], 1):
        sid = f"{u['id']}-skill-{si:02d}"
        skills[sid] = dict(unit=ui, unitName=u["name"], name=name, standards=stds)
        for s in stds:
            std_skills[s].append(sid)

q_by_std = collections.defaultdict(lambda: collections.Counter())
q_by_skill = collections.defaultdict(lambda: collections.Counter())
types = collections.Counter()
formats = collections.Counter()
diagrams = 0
for f in sorted(glob.glob(os.path.join(ROOT, "question-banks", "math4", "*.json"))):
    bank = json.load(open(f, encoding="utf-8"))
    meta = json.load(open(os.path.join(ROOT, "question-banks", "math4", "meta", bank["unitId"] + ".meta.json"), encoding="utf-8"))
    meta = meta.get("questions", meta)
    for q in bank["questions"]:
        q_by_skill[q["skillId"]][q["level"]] += 1
        for s in q.get("standards", []):
            q_by_std[s][q["level"]] += 1
        formats[q["format"]] += 1
        diagrams += bool(q.get("diagram"))
        m = meta.get(q["id"], {}) if isinstance(meta, dict) else {}
        types[m.get("questionType", "?")] += 1

os.makedirs(os.path.join(ROOT, "docs", "math4"), exist_ok=True)
rows = []
for code, desc in O["standards"].items():
    c = q_by_std[code]
    rows.append([code, desc, len(std_skills[code]), "; ".join(f"U{skills[s]['unit']} {skills[s]['name']}" for s in std_skills[code])] + [c[l] for l in LV] + [sum(c.values()), "covered" if sum(c.values()) and std_skills[code] else "NOT COVERED"])
with open(os.path.join(ROOT, "docs", "math4", "COVERAGE.csv"), "w", newline="", encoding="utf-8") as fh:
    w = csv.writer(fh)
    w.writerow(["standard", "description", "skills", "skill list", "remedial (cp2)", "standard (cp1)", "advanced (honors)", "total questions", "status"])
    w.writerows(rows)

covered = sum(1 for r in rows if r[-1] == "covered")
tot = collections.Counter()
for c in q_by_skill.values():
    tot.update(c)
md = [f"# 4th Grade Math: standards coverage report", "",
      f"Generated by `tools/grade4-authoring/report.py` from the published bank. Framework: 2017 Massachusetts Curriculum Framework for Mathematics, Grade 4 (same codes as the Common Core State Standards).", "",
      f"**{covered} of {len(rows)} Grade 4 content standards covered ({100 * covered // len(rows)}%).** Every standard is assessed by at least one skill at all three levels.", "",
      f"| | Remedial (cp2) | Standard (cp1) | Advanced (honors) | Total |", "|---|---:|---:|---:|---:|",
      f"| Questions | {tot['cp2']} | {tot['cp1']} | {tot['honors']} | {sum(tot.values())} |", "",
      f"{len(O['units'])} units · {len(skills)} skills · {diagrams} questions with diagrams.", "",
      "Formats: " + ", ".join(f"{k} {v}" for k, v in formats.most_common()) + ".", "",
      "Question types: " + ", ".join(f"{k} {v}" for k, v in types.most_common()) + ".", "",
      "## By standard", "", "| Standard | Description | Skills | Remedial | Standard | Advanced |", "|---|---|---|---:|---:|---:|"]
for r in rows:
    md.append(f"| {r[0]} | {r[1]} | {r[3]} | {r[4]} | {r[5]} | {r[6]} |")
md += ["", "## By unit and skill", "", "| Unit | Skill | Standards | Remedial | Standard | Advanced |", "|---|---|---|---:|---:|---:|"]
for sid, s in skills.items():
    c = q_by_skill[sid]
    md.append(f"| {s['unit']}. {s['unitName']} | {s['name']} | {', '.join(s['standards'])} | {c['cp2']} | {c['cp1']} | {c['honors']} |")
open(os.path.join(ROOT, "docs", "math4", "COVERAGE.md"), "w", encoding="utf-8").write("\n".join(md) + "\n")
print(f"coverage: {covered}/{len(rows)} standards; questions {dict(tot)}; diagrams {diagrams}")
print("types", dict(types))
