"""Write docs/math2/COVERAGE.md from the published Grade 2 banks."""
import json, os, sys
from collections import Counter
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.abspath(os.path.join(HERE, "..", "grade1-authoring")))
from outline2 import UNITS, COURSE_ID

L = []
def w(s=""):
    L.append(s)

banks, metas = {}, {}
for u in UNITS:
    banks[u["id"]] = json.load(open(os.path.join(ROOT, "question-banks", COURSE_ID, u["id"] + ".json"), encoding="utf-8"))["questions"]
    metas[u["id"]] = json.load(open(os.path.join(ROOT, "question-banks", COURSE_ID, "meta", u["id"] + ".meta.json"), encoding="utf-8"))

fmt, qtype, stds = Counter(), Counter(), Counter()
total = diagrams = 0
per_unit = {}
for u in UNITS:
    qs = banks[u["id"]]
    n = len(qs)
    dg = sum(1 for q in qs if q.get("diagram"))
    per_unit[u["id"]] = (n, dg)
    total += n
    diagrams += dg
    for q in qs:
        fmt[q["format"]] += 1
        qtype[metas[u["id"]].get(q["id"], {}).get("questionType", "?")] += 1
        for s in q.get("standards") or []:
            stds[s] += 1

before = json.load(open(os.path.join(HERE, "out", "dup_before.json")))
after = json.load(open(os.path.join(HERE, "out", "dup_after.json")))["after"]

w("# Grade 2 Mathematics (math2) — bank coverage")
w()
w(f"**{total:,} questions · {len(UNITS)} units · {sum(len(u['skills']) for u in UNITS)} skills · 3 levels · {diagrams:,} diagrams**")
w()
w("Generated by `tools/grade2-authoring/report2.py` from the published banks.")
w()
w("## Question formats")
w()
w("| Format | Count | Share |")
w("|---|---:|---:|")
for k, v in fmt.most_common():
    w(f"| {k} | {v:,} | {v / total * 100:.1f}% |")
w()
w("## Question types (meta)")
w()
w("| Type | Count |")
w("|---|---:|")
for k, v in qtype.most_common():
    w(f"| {k} | {v:,} |")
w()
w("## Units")
w()
w("| Unit | Days | Skills | Questions | Diagrams |")
w("|---|---|---:|---:|---:|")
for u in UNITS:
    n, dg = per_unit[u["id"]]
    d0, d1 = u["days"]
    w(f"| {u['name']} | {d0}–{d1} | {len(u['skills'])} | {n:,} | {dg} |")
w()
for u in UNITS:
    w(f"### {u['name']}")
    w()
    w("| # | Skill | Standard(s) | Questions |")
    w("|---:|---|---|---:|")
    counts = Counter(q["skillId"] for q in banks[u["id"]])
    for i, nm in enumerate(u["skills"], 1):
        sid = f"{u['id']}-skill-{i:02d}"
        w(f"| {i} | {nm} | {', '.join((u['standards_by_skill'].get(nm) or u['standards'])[:4])} | {counts[sid]} |")
    w()
w("## Standards coverage")
w()
w("| Standard | Questions |")
w("|---|---:|")
for s in sorted(stds):
    w(f"| {s} | {stds[s]:,} |")
w()
w(f"Total distinct Grade 2 standard codes: **{len(stds)}**.")
w()
w("## Cross-skill duplication")
w()
w("| Measure | Before | After |")
w("|---|---:|---:|")
w(f"| Items that duplicate a question in another skill | {before['dup_items']:,} | {after['dup_items']:,} |")
w(f"| Share of the bank | {before['dup_rate'] * 100:.1f}% | {after['dup_rate'] * 100:.1f}% |")
w(f"| Redundant copies | {before['excess']:,} | {after['excess']:,} |")
w(f"| Picture-equivalent groups | {before['vis_groups']:,} | {json.load(open(os.path.join(HERE, 'out', 'dup_after.json')))['vis_groups_after']:,} |")
w()
w("No question repeats inside its own skill and difficulty level (checked by the verifier). The")
w("remaining repetition is confined to closed picturable fact sets — arrays of a given size, the four")
w("polygon names, halves/thirds/fourths wording, true/false stems and short place-value questions —")
w("where meeting the same item again is fluency practice.")
w()
w("## Validation")
w()
w("| Check | Result |")
w("|---|---|")
w(f"| Questions verified | {total:,} |")
w("| Answers re-derived from stored inputs by an independent verifier | all |")
w("| Mathematical errors | 0 |")
w(f"| Diagrams present, 720×480, decodable, not blank | {diagrams:,} |")
w("| Diagram defects | 0 |")
w("| Duplicates inside a skill/level | 0 |")
w("| Questions per skill and level | 30 (12 short answer, 12 multiple choice, 3 error analysis, 1 true/false, 1 select-all, 1 open response) |")
w()
w("Verifier: `python3 tools/grade2-authoring/verify2.py` → `TOTAL ERRORS 0`.")
w()
w("## Approval status")
w()
w("| Field | Value |")
w("|---|---|")
w("| Mathematical validation | passed — independent verifier, 0 errors |")
w("| Editorial review | not performed |")
w("| Manifest `approved` | `false` for all 9 units |")
w()
w("The banks are mathematically validated but **not editorially approved**, and they are not")
w("integrated into either site.")

out = os.path.join(ROOT, "docs", COURSE_ID)
os.makedirs(out, exist_ok=True)
open(os.path.join(out, "COVERAGE.md"), "w", encoding="utf-8").write("\n".join(L) + "\n")
print("wrote docs/math2/COVERAGE.md", total, "questions,", diagrams, "diagrams")

# Keep review metadata synchronized with the committed banks and the audit output.
# This updates only the math2 manifest's non-approval summary fields, never
# question items, statuses, or editorial approval flags.
import re
import subprocess

manifest_path = os.path.join(ROOT, "question-banks", COURSE_ID, "manifest.json")
with open(manifest_path, encoding="utf-8") as fh:
    manifest = json.load(fh)
assert manifest["courseId"] == COURSE_ID
assert len(manifest["banks"]) == len(UNITS)
assert not manifest["review"]["editorialApproval"]["approved"]
assert all(b["approved"] is False for b in manifest["banks"])

levels_text = open(os.path.join(ROOT, "docs", COURSE_ID, "LEVELS.md"), encoding="utf-8").read()
level_match = re.search(r"Skills:\s*(\d+),\s*flat:\s*(\d+)", levels_text)
if not level_match:
    raise RuntimeError("Grade 2 level report does not contain a skill summary")
skills_checked, skills_flat = map(int, level_match.groups())
assert skills_checked == sum(len(u["skills"]) for u in UNITS)

audit = subprocess.run([sys.executable, os.path.join(HERE, "audit2.py")],
                       cwd=HERE, capture_output=True, text=True, check=True)
audit_match = re.search(r"TOTAL FLAGGED\s+(\d+)", audit.stdout)
if not audit_match:
    raise RuntimeError("Grade 2 semantic audit did not report a candidate count")
semantic_candidates = int(audit_match.group(1))

validation = manifest["review"]["mathematicalValidation"]
validation["questionsChecked"] = total
validation["diagrams"] = diagrams
validation["exactCrossSkillDuplicateRate"] = round(after["dup_rate"], 4)
validation["semanticAudit"] = (
    f"screened (tools/grade2-authoring/audit2.py: {semantic_candidates} "
    "rule-based candidates, not confirmed defects)"
)
dedup = manifest["review"]["deduplication"]
dedup["exactCrossSkillDuplicates"] = after["dup_items"]
dedup["rate"] = round(after["dup_rate"], 4)
# Earlier postprocessing counts have no authoritative stored per-action source.
for legacy_field in ("replaced", "leftAsClosedFactSets", "keptAsIntentionalRepetition"):
    dedup.pop(legacy_field, None)
dedup["redundantCopies"] = after["excess"]
dedup["pictureEquivalentGroups"] = after["vis_groups"]
levels = manifest["review"]["levelEscalation"]
levels["skillsChecked"] = skills_checked
levels["skillsNotEscalating"] = skills_flat
levels["status"] = "passed" if skills_flat == 0 else "passed-with-exceptions"
with open(manifest_path, "w", encoding="utf-8") as fh:
    json.dump(manifest, fh, ensure_ascii=False, indent=1)
    fh.write("\n")
print("updated math2 manifest metrics:", total, diagrams,
      semantic_candidates, "semantic candidates;", skills_flat, "flat skills")

