def skill_records(unit):
    return [dict(id=f"{unit['id']}-skill-{i:02d}", index=i, name=s[0], standards=s[1], target=s[2], misconception=s[3], fix=s[4])
            for i, s in enumerate(unit["skills"], 1)]


def all_skills():
    for u in UNITS:
        for r in skill_records(u):
            yield u, r


