def ws_html(t, key):
    cname = GRADE_WORD[t["grade"]]
    qs = t["worksheet"]

    def page(body):
        return (f'<div class="pg"><div class="ban">{"<span class=key>TEACHER KEY</span>" if key else ""}<h1>{html.escape(t["title"])}</h1>'
                f'<p>{cname} · Interactive Math · Explore &amp; Reflect</p></div>'
                + ('' if key else '<div class="meta"><span>Name:</span><span>Date:</span><span>Class:</span></div>') + body +
                f'<div class="ft">Use with the {html.escape(t["title"])} at mrksclassroom.com · Mr. K’s Classroom</div></div>')

    def block(items, start):
        return "".join(f'<div class="q"><b>{start + i + 1}.</b> {html.escape(q)}</div>' +
                       (f'<div class="ans">{html.escape(a)}</div>' if key else '<div class="ln"></div><div class="ln"></div>')
                       for i, (q, a) in enumerate(items))
    p1 = page(f'<div class="box"><h2>Get started</h2><div style="font-size:11pt">{html.escape(t["description"])} '
              f'Open the tool and use it to answer each question.</div></div><div class="box"><h2>Explore</h2>{block(qs[:4], 0)}</div>')
    tn = ('<div class="box" style="border-color:#f08c1a"><h2 style="color:#b45309">Teacher notes</h2><ul class="tn">' +
          "".join(f"<li>{html.escape(x)}</li>" for x in t["teacher"]) +
          f'</ul><div style="font-size:10pt;margin-top:.05in"><b>Standards:</b> {html.escape(t["standards"])}. '
          'Accept any correct answer where several are possible, and ask students to explain with the tool’s picture.</div></div>') if key else ''
    p2 = page(f'<div class="box"><h2>Explore more</h2>{block(qs[4:6], 4)}</div><div class="box" style="border-color:#1fa565"><h2>Reflect</h2>{block(qs[6:], 6)}'
              + ('' if key else '<div class="ln"></div>') + '</div>' + tn)
    return f"<!doctype html><html><head><meta charset=utf-8><style>{CSS}</style></head><body>{p1}{p2}</body></html>"


