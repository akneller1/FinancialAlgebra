"""Grade 1–3 Interactive Math tools: pages, manifests, Explore & Reflect worksheets, teacher keys and thumbnails.

Usage (from the repository root):
  python3 tools/elementary-interactive/build.py            # writes artifacts/math{1,2,3}-*/index.html and the three
                                                           # tools/grade{1,2,3}-authoring/interactive/manifest.json files
  python3 tools/elementary-interactive/build.py --print    # also prints worksheet.pdf, teacher-key.pdf and thumbs/<slug>.svg
                                                           # (needs Playwright's Chromium; serves the repo on localhost:8766)
  node tools/elementary-interactive/tests/browser-tools.cjs   # every tool loads cleanly and every challenge can be reached

Each tool page follows the Grade 5 Interactive Math model (artifacts/math5-*): a live model with + / − controls, a "Try this"
list that ticks off as students meet each goal, a closed "What should I notice?" panel, Teacher view with notes, standards and
links to the worksheet and key, and zoom / Fit / Present / Reset from the shared elementary shell. No network calls.
"""
import html, json, os, re, subprocess, sys, base64, threading, http.server, functools

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, HERE)
from reg import TOOLS, COURSES  # noqa: E402
import tools_g1, tools_g2, tools_g3  # noqa: E402,F401

