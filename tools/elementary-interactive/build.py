def write_pages():
    seen = set()
    for t in TOOLS:
        assert t["slug"] not in seen, t["slug"]
        seen.add(t["slug"])
        cid, cname = COURSES[t["grade"]]
        meta = dict(course=cid, courseName=cname, unit=t["units"][0], title=t["title"], standards=t["standards"],
                    notice=t["notice"], teacher=t["teacher"])
        page = PAGE.format(title=html.escape(t["title"]), course_name=cname, desc=html.escape(t["description"], quote=True),
                           intro=html.escape(t["intro"]), body=t["body"].strip(), v=V,
                           meta=json.dumps(meta, ensure_ascii=False), script=t["script"].strip())
        d = os.path.join(ROOT, "artifacts", t["slug"])
        os.makedirs(d, exist_ok=True)
        open(os.path.join(d, "index.html"), "w", encoding="utf-8").write(page)
    # manifests read by tools/grade{N}-authoring/staging/assemble-grade{N}.mjs
    for g in (1, 2, 3):
        units = {u["id"] for u in json.load(open(os.path.join(ROOT, f"tools/grade{g}-authoring/outline.json")))["units"]}
        items = []
        for t in TOOLS:
            if t["grade"] != g:
                continue
            bad = [u for u in t["units"] if u not in units]
            assert not bad, (t["slug"], bad)
            items.append(dict(slug=t["slug"], units=t["units"], title=t["title"], description=t["description"], topics=t["topics"],
                              standards=t["standards"], worksheet=t["worksheet"]))
        f = os.path.join(ROOT, f"tools/grade{g}-authoring/interactive/manifest.json")
        os.makedirs(os.path.dirname(f), exist_ok=True)
        json.dump({"tools": items}, open(f, "w", encoding="utf-8"), indent=1, ensure_ascii=False)
        open(f, "a").write("\n")
    print(len(TOOLS), "tool pages; manifests for grades 1–3 written")


