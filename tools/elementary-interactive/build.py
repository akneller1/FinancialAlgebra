def print_all():
    tmp = "/tmp/el-interactive-print"
    os.makedirs(tmp, exist_ok=True)
    jobs = []
    for t in TOOLS:
        for key in (False, True):
            f = os.path.join(tmp, f'{t["slug"]}-{"key" if key else "ws"}.html')
            open(f, "w", encoding="utf-8").write(ws_html(t, key))
            jobs.append({"html": f, "pdf": os.path.join(ROOT, "artifacts", t["slug"], "teacher-key.pdf" if key else "worksheet.pdf")})
        jobs.append({"url": f"http://localhost:8766/artifacts/{t['slug']}/index.html?student=1", "jpg": os.path.join(tmp, t["slug"] + ".jpg"),
                     "w": 1280, "h": 600, "outW": 960, "wait": 400})
    json.dump(jobs, open(os.path.join(tmp, "jobs.json"), "w"))
    class Quiet(http.server.SimpleHTTPRequestHandler):
        def log_message(self, *a):
            pass
    handler = functools.partial(Quiet, directory=ROOT)
    srv = http.server.ThreadingHTTPServer(("127.0.0.1", 8766), handler)
    threading.Thread(target=srv.serve_forever, daemon=True).start()
    try:
        subprocess.run(["node", os.path.join(ROOT, "tools/grade3-authoring/print/print.cjs"), os.path.join(tmp, "jobs.json")], check=True)
    finally:
        srv.shutdown()
    for t in TOOLS:
        img = base64.b64encode(open(os.path.join(tmp, t["slug"] + ".jpg"), "rb").read()).decode()
        title = html.escape(t["title"])
        open(os.path.join(ROOT, "thumbs", t["slug"] + ".svg"), "w", encoding="utf-8").write(
            THUMB.format(title=title, img=img, fs=30 if len(t["title"]) < 30 else 25, grade=GRADE_WORD[t["grade"]]))
    print("printed worksheets, keys and thumbnails for", len(TOOLS), "tools")


if __name__ == "__main__":
    write_pages()
    if "--print" in sys.argv:
        print_all()
