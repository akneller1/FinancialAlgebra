"""Write docs/math1/COVERAGE.md from the published Grade 1 banks."""
import json, os, sys
from collections import Counter, defaultdict
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, HERE)
from outline import UNITS, COURSE_ID, skill_records

LINES = []
def w(s=""): LINES.append(s)

tot = Counter(); per_unit = {}
fmt = Counter(); dg = Counter(); qtype = Counter(); stds = Counter()
meta_dir = os.path.join(ROOT, "question-banks", COURSE_ID, "meta")
for u in UNITS:
    bank = json.load(open(os.path.join(ROOT, "question-banks", COURSE_ID, u["id"] + ".json"), encoding="utf-8"))
    meta = json.load(open(os.path.join(meta_dir, u["id"] + ".meta.json"), encoding="utf-8"))
    recs = {r["id"]: r for r in skill_records(u)}
    counts = Counter(); dfmt = Counter(); ddg = 0; pages = u["days"]
    for q in bank["questions"]:
        counts[q["skillId"]] += 1
        dfmt[q["format"]] += 1
        fmt[q["format"]] += 1
        qtype[meta.get(q["id"], {}).get("questionType", "?")] += 1
        if q.get("diagram"):
            ddg += 1; dg[u["id"]] += 1
        for s in q.get("standards") or []:
            stds[s] += 1
        tot["q"] += 1
    per_unit[u["id"]] = (len(bank["questions"]), ddg, dfmt, counts, recs, pages)
    tot["diagrams"] += ddg

w("# Grade 1 Mathematics (math1) — bank coverage")
w()
w(f"**{tot['q']:,} questions · {len(UNITS)} units · {{skills}} skills · 3 levels · {tot['diagrams']:,} diagrams**")
w()
w("Generated by `tools/grade1-authoring/report.py` from the published banks.")
w()
w("## Question formats")
w()
w("| Format | Count | Share |")
w("|---|---:|---:|")
for k, v in fmt.most_common():
    w(f"| {k} | {v:,} | {v / tot['q'] * 100:.1f}% |")
w()
w("## Question types (meta)")
w()
w("| Type | Count |")
w("|---|---:|")
for k, v in qtype.most_common():
    w(f"| {k} | {v:,} |")
w()
w("## Units")
w()
w("| Unit | Days | Skills | Questions | Per skill | Diagrams |")
w("|---|---|---:|---:|---:|---:|")
skills_total = 0
for u in UNITS:
    n, ddg, dfmt, counts, recs, pages = per_unit[u["id"]]
    skills_total += len(recs)
    per = ", ".join(f"{counts[r['id']]}" for r in recs.values())
    uniq = sorted(set(counts.values()))
    w(f"| {u['name']} | {pages[0]}–{pages[1]} | {len(recs)} | {n:,} | {uniq[0] if len(uniq)==1 else per} | {ddg} |")
w()
for u in UNITS:
    n, ddg, dfmt, counts, recs, pages = per_unit[u["id"]]
    w(f"### {u['name']}")
    w()
    w("| # | Skill | Standard(s) | Questions |")
    w("|---:|---|---|---:|")
    for r in recs.values():
        w(f"| {r['index']} | {r['name']} | {', '.join(r['standards'])} | {counts[r['id']]} |")
    w()
w("## Standards coverage")
w()
w("| Standard | Questions |")
w("|---|---:|")
for s in sorted(stds):
    w(f"| {s} | {stds[s]:,} |")
w()
w(f"Total distinct Grade 1 standard codes: **{len(stds)}**.")


# ---------------------------------------------------------------- duplication and validation
import dupstats
qs = []
for u in UNITS:
    for q in json.load(open(os.path.join(ROOT, "question-banks", COURSE_ID, u["id"] + ".json"), encoding="utf-8"))["questions"]:
        q["_id"] = dupstats.ident(q)
        q["_shape"] = dupstats.shape(q)
        qs.append(q)
after, _, vis_after = dupstats.stats(qs, verbose=False)
before = json.load(open(os.path.join(HERE, "out", "dup_before.json")))
dp = json.load(open(os.path.join(HERE, "out", "dedupe_stats.json")))

w("## Cross-skill duplication")
w()
w("A duplicate is counted when the same question identity (prompt, options, answer and picture description)")
w("appears in two different skills. One copy of every identity is always kept: repeating a fact inside")
w("different skills is normal practice, but copying a whole question is not.")
w()
w("| Measure | Before (`563132c`) | After |")
w("|---|---:|---:|")
w(f"| Items that duplicate another skill | {before['dup_items']:,} | {after['dup_items']:,} |")
w(f"| Share of the bank | {before['dup_rate'] * 100:.1f}% | {after['dup_rate'] * 100:.1f}% |")
w(f"| Distinct identities duplicated | {before['dup_groups']:,} | {after['dup_groups']:,} |")
w(f"| Redundant copies (same identity twice or more) | {before['excess']:,} | {after['excess']:,} |")
w(f"| Picture-equivalent groups (same picture and answer) | {before['vis_groups']:,} | {len(vis_after):,} |")
w()
w(f"The pass rewrote {dp['replaced_total']:,} of the {dp['redundant_copies']:,} redundant copies:")
w()
w("| Replacement route | Items |")
w("|---|---:|")
w(f"| Fresh draw from the same family (new numbers, original form) | {dp['replaced']['fresh_family_draw']:,} |")
w(f"| Fresh draw re-presented in another task form | {dp['replaced']['fresh_draw_represented']:,} |")
w(f"| Same fact re-presented without the picture | {dp['replaced']['same_fact_represented_without_picture']:,} |")
w(f"| Left in place as intentional repetition | {dp['kept_as_intentional_repetition']:,} |")
w()
w("Repetition that was deliberately preserved: clock times (24 readings a day), the six plane shapes and")
w("four solids, `equal parts` wording, and true/false stems built on the same fact. These are small closed")
w("fact sets where meeting the same item again is reinforcement, not an authoring error; the wording still")
w("varies and no item repeats inside its own skill and level.")
w()
w(f"No question repeats inside one skill and difficulty level: {tot['q']:,} items, 0 within-skill duplicates.")
w()
w("## Validation")
w()
w("| Check | Result |")
w("|---|---|")
w(f"| Questions verified | {tot['q']:,} |")
w(f"| Answers re-derived independently from stored inputs | {tot['q']:,} of {tot['q']:,} |")
w("| Mathematical errors | 0 |")
w(f"| Diagrams present and decodable | {tot['diagrams']:,} |")
w("| Diagram defects (missing, wrong size, blank, alt/answer mismatch) | 0 |")
w("| Duplicates inside a skill/level | 0 |")
w("| Questions per skill and level | 30 (12 short answer, 12 multiple choice, 3 error analysis, 1 true/false, 1 select-all, 1 open response) |")
w()
w("Verifier: `python3 tools/grade1-authoring/verify1.py` → `TOTAL ERRORS 0`.")
w(f"The diagram count is {dp['diagrams_after']:,}, down from {dp['diagrams_before']:,}: re-presented arithmetic items are")
w("text-form tasks, and the copy that keeps the picture is always the one retained.")
w()
w("## Approval status")
w()
w("| Field | Value |")
w("|---|---|")
w("| Mathematical validation (`approved` for maths) | passed — independent verifier, 0 errors |")
w("| Editorial review | not performed |")
w("| Bank manifest `approved` | `false` for all 8 units |")
w()
w("The banks are mathematically validated but **not editorially approved**. They stay unapproved in")
w("`question-banks/math1/manifest.json` until a reviewer signs off, and they are not integrated into any site.")

lines = "\n".join(LINES).replace("{skills}", str(skills_total)) + "\n"
out = os.path.join(ROOT, "docs", "math1")
os.makedirs(out, exist_ok=True)
open(os.path.join(out, "COVERAGE.md"), "w", encoding="utf-8").write(lines)
print("wrote docs/math1/COVERAGE.md", tot["q"], "questions,", tot["diagrams"], "diagrams")
