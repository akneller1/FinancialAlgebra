/* Grade 1 development-only assembly. Reuses the Grade 2 shared game and Understanding Check runtime.
   This question-bank package does not yet supply flashcards, cheat sheets, vocabulary or projects. */
import fs from 'node:fs';
import path from 'node:path';

const C = 'math1', G = 'grade1', V = 'grade1-preview-20261113';

export function grade1Ready(source) {
  const m = JSON.parse(fs.readFileSync(path.join(source, 'manifest.json'), 'utf8'));
  return m.banks.some(b => b.courseId === C && (b.approved === true || b.preview === true));   // preview: development only, never production
}

export function assembleGrade1({ source, out }) {
  const tools = path.join(source, 'tools/grade1-authoring');
  const O = JSON.parse(fs.readFileSync(path.join(tools, 'outline.json'), 'utf8'));
  const GAMES = JSON.parse(fs.readFileSync(path.join(tools, 'games.json'), 'utf8')).games;
  const TOOLS = [];
  const PROJ = {};
  const dest = path.join(out, G);
  fs.rmSync(dest, { recursive: true, force: true });
  const copy = (from, to = from, root = source) => {
    const a = path.join(root, from), b = path.join(dest, to);
    if (!fs.existsSync(a)) throw Error('Grade 1 preview: missing ' + from);
    fs.mkdirSync(path.dirname(b), { recursive: true });
    fs.cpSync(a, b, { recursive: true });
  };
  const list = (dir, re) => fs.readdirSync(path.join(source, dir)).filter(f => re.test(f)).map(f => dir + '/' + f);

  /* 1. course-owned files (same relative layout as the production repository) */
  ['worksheet-generator/grade1-games.html', 'worksheet-generator/grade1-understanding-check.html',
    'worksheet-generator/elementary', 'worksheet-generator/grade1', 'question-banks/math1', 'question-banks/assets/math1']
    .concat(list('artifacts', /^math1-/), list('thumbs', /^math1-/)).forEach(f => copy(f));
  /* 2. shared Classroom files the players use, taken from the assembled production shell */
  ['question-bank-adapter.js', 'question-bank-loader.js', 'analytics.js', 'assets/favicon.svg', 'worksheet-generator/core/math-display.js',
    'worksheet-generator/core/math-display.css', 'worksheet-generator/games/skill-setup.js'].forEach(f => { if (fs.existsSync(path.join(out, f))) copy(f, f, out); });
  /* 3. generated course record, skill catalog and bank manifest for the players */
  const course = { id: C, name: O.name, color: 'green', art: 'first', blurb: O.blurb, units: O.units.map(u => ({ id: u.id, name: u.name, artifacts: [] })) };
  fs.writeFileSync(path.join(dest, 'data.js'), `/* Generated by tools/grade1-authoring/staging/assemble-grade1.mjs. */\nwindow.LIBRARY={courses:[${JSON.stringify(course)}]};\n`);
  const skills = Object.fromEntries(O.units.map(u => [u.id, u.skills.map(s => s[0])]));
  fs.writeFileSync(path.join(dest, 'course-catalog.js'), `/* Generated by tools/grade1-authoring/staging/assemble-grade1.mjs. */
(function(G){var S=${JSON.stringify(skills)};function rec(c,u){return c==='${C}'&&S[u]?S[u].map(function(n,i){return {id:u+'-skill-'+String(i+1).padStart(2,'0'),name:n,index:i+1};}):[];}
G.MK_COURSE_CATALOG={getSkills:function(c,u){return rec(c,u).map(function(r){return r.name;});},getSkillRecords:rec,courses:function(){return ['${C}'];}};})(window);\n`);
  const banks = O.units.map(u => ({ courseId: C, unitId: u.id, path: `question-banks/${C}/${u.id}.json`, approved: true }));
  const playerManifest = JSON.stringify({ version: 1, banks }, null, 2) + '\n';
  fs.writeFileSync(path.join(dest, 'question-banks/manifest.json'), playerManifest);
  // The shared loader resolves '../manifest.json' relative to grade1/worksheet-generator/.
  // Keep its root manifest in sync rather than making a separate player engine.
  fs.writeFileSync(path.join(dest, 'manifest.json'), playerManifest);
  // The players return to the course page; /grade1/ itself is only an alias of /#grade1.
  fs.writeFileSync(path.join(dest, 'index.html'), '<!doctype html><html><head><meta charset="utf-8"><meta name="robots" content="noindex"><script>location.replace("../#grade1"+(location.hash.replace(/^#(?:c\\/)?(?:math|grade)2\\.?/,"")?"."+location.hash.replace(/^#(?:c\\/)?(?:math|grade)2\\.?/,""):""));</script></head><body><a href="../#grade1">Open Grade 1</a></body></html>\n');
  // analytics stays off on the noindex development preview
  if (fs.existsSync(path.join(dest, 'analytics.js'))) fs.writeFileSync(path.join(dest, 'analytics.js'), '/* development preview: analytics disabled */\n');

  /* Native planner teaching notes and the Activity generator's project registry, the way released Grade 5 supplies them. */
  const notes = {};
  fs.writeFileSync(path.join(dest, 'grade1-native-notes.js'), 'window.MKPLAN_TEACH=window.MKPLAN_TEACH||{};window.MKPLAN_TEACH.' + G + '=' + JSON.stringify(notes) + ';\n');
  const nativeProjects = {};
  Object.entries(PROJ).forEach(([k, list]) => { nativeProjects[k.replace(/^math1-/, G + '-')] = list.map(p => ({ folder: p.folder, slug: p.slug, base: '../' + G + '/artifacts/' + p.folder + '/',
    thumb: '../' + G + '/thumbs/' + p.folder + '.svg', title: p.title, tagline: p.tagline || p.description, description: p.description, theme: 'Grade 1 Math', product: 'Project packet' })); });
  fs.writeFileSync(path.join(dest, 'grade1-native-resources.js'), 'if(window.MKMENU&&MKMENU.printables)MKMENU.printables.PROJECTS=Object.assign(MKMENU.printables.PROJECTS||{},' + JSON.stringify(nativeProjects) + ');\n');
  [['lesson-planner.html', '<script src="planner/scope-algebra2.js', 'native-notes'], ['printables.html', '<script src="menu/printables-match.js', 'native-resources']].forEach(([page, anchor, name]) => {
    const f = path.join(out, 'worksheet-generator', page);
    if (!fs.existsSync(f)) return;
    let html = fs.readFileSync(f, 'utf8');
    if (html.includes('grade1-' + name + '.js')) return;
    if (!html.includes(anchor)) throw Error('Grade 1 preview: anchor not found in ' + page + ': ' + anchor);
    fs.writeFileSync(f, html.replace(anchor, '<script src="../' + G + '/grade1-' + name + '.js?v=' + V + '"></script>\n' + anchor));
  });
  /* The production planner (planner-ui.js) waits for course banks only for the courses in its approved-bank list,
     which does not name grade1 yet (see tools/grade1-authoring/INTEGRATION.md). Without that wait, the first day it draws for a Grade 1
     unit can be drawn before the banks finish loading, with every slot empty. This preview-only helper redraws that day
     once the banks are ready, and only when no slot holds a problem (so nothing a teacher chose is replaced). */
  {
    const f = path.join(out, 'worksheet-generator/lesson-planner.html');
    let html = fs.readFileSync(f, 'utf8');
    if (!html.includes('grade1-planner-ready')) {
      const js = '<script id="grade1-planner-ready">(function(G){var done=false;function fix(){if(done||G.MKPLAN_COURSE!=="' + G + '")return;var s=G.document.querySelector(".pl-stat"),m=s&&/(\\d+) problems · (\\d+) need a new problem/.exec(s.textContent);var b=G.document.getElementById("plNew");if(m&&m[1]===m[2]&&b){done=true;b.click();}}' +
        'G.addEventListener("load",function(){(G.MK_COURSE_BANKS_READY||Promise.resolve()).then(function(){G.setTimeout(fix,300);G.setTimeout(fix,1500);});});})(window);</script>\n';
      fs.writeFileSync(f, html.replace('</body>', js + '</body>'));
    }
  }

  /* 4. the unit cards: native generators first, then the Grade 1 players, study guides, tools and projects */
  const LV = ['Remedial', 'Standard', 'Advanced'];
  const exists = p => { if (!fs.existsSync(path.join(out, p.split(/[?#]/)[0]))) throw Error('Grade 1 preview: missing ' + p); return p; };
  const units = O.units.map((u, i) => {
    const set = G + '-' + u.id, A = [];
    const add = a => A.push(Object.assign({ level: LV }, a, { path: exists(a.path), thumb: exists(a.thumb) }));
    [['Lesson Plan', 'lesson-planner.html', 'lesson-planner', 'lesson', 'Printable lesson: guided and completed notes, worked examples, practice, mixed review, challenge problems and a teacher key.'],
      ['Worksheet', 'worksheet.html', 'worksheet-generator', 'worksheet', 'Choose skills, level, question types, count and work space; print with an answer key.'],
      ['Activity', 'printables.html', 'printable-generator', 'activity', 'Mazes, color by number, matching, Tarsia, stations, partner checks and more, with teacher keys.'],
      ['Assessment', 'menu-assessment.html', 'assessment-generator', 'assessment', 'Multiple choice, short answer and open response, with points, versions and an answer key.']]
      .forEach(([t, page, fmt, th, d]) => add({ title: t + ' Generator', path: 'worksheet-generator/' + page + '#unit=' + set, type: 'Generator', bankFormat: fmt, thumb: `${G}/thumbs/math1-generator-${th}.svg`, description: d }));
    add({ title: 'Error Analysis', path: 'worksheet-generator/printables.html#unit=' + set + '&kind=error', type: 'Generator', bankFormat: 'printable-generator', visibleInBrowse: true, thumb: `${G}/thumbs/math1-generator-activity.svg`, description: 'Find, explain and correct a classmate’s mistake. Teacher solutions included.' });
    GAMES.forEach(g => {
      if (g.units && !g.units.includes(u.id)) return;
      add({ title: g.title, path: `${G}/worksheet-generator/grade1-games.html?game=${g.id}&unit=${u.id}`, type: 'Game', bankFormat: g.id === 'four-in-a-row' ? 'connect-four' : 'topic-games', gameMode: g.team ? 'Team Games' : 'Individual Review', thumb: `${G}/thumbs/math1-game-${g.thumb}.svg`, description: g.description });
    });
    add({ title: 'Understanding Check', path: `${G}/worksheet-generator/grade1-understanding-check.html?unit=${u.id}`, type: 'Study Guide', bankFormat: 'interactive-practice-test', thumb: `${G}/thumbs/math1-understanding-check.svg`, description: 'Immediate feedback, worked solutions, progress, a summary, retry of missed questions and a printable results page.' });
    TOOLS.filter(t => t.units.includes(u.id)).forEach(t => add({ title: t.title, path: `${G}/artifacts/${t.slug}/index.html`, type: 'Interactive', bankFormat: 'interactive-math', thumb: `${G}/thumbs/${t.slug}.svg`, description: t.description }));
    (PROJ['math1-' + u.id] || []).forEach(p => add({ title: p.title, path: `${G}/artifacts/${p.folder}/index.html`, type: 'Project', bankFormat: 'other', thumb: `${G}/thumbs/${p.folder}.svg`, description: p.description }));
    return { id: u.id, name: u.name, artifacts: A };
  });
  let nQ = 0;
  O.units.forEach(u => { nQ += JSON.parse(fs.readFileSync(path.join(source, `question-banks/${C}/${u.id}.json`), 'utf8')).questions.length; });
  const nS = O.units.reduce((n, u) => n + u.skills.length, 0);
  return { id: G, name: O.name, blurb: O.blurb, color: 'green', art: 'first', preloaded: true,
    approved: `${nS} skills · ${nQ.toLocaleString('en-US')} verified questions · games and understanding checks`, units,
    skills: Object.fromEntries(O.units.map(u => [u.id, u.skills.map(s => s[0])])) };
}
